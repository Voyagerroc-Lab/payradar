    fun t(key: String, lang: AppLanguage = AppLanguage.TR, params: Map<String, Any> = emptyMap()): String {
        val dict = when (lang) {
            AppLanguage.EN -> en
            AppLanguage.MS -> ms
            AppLanguage.TR -> tr
        }
        var text = dict[key] ?: tr[key] ?: key
        for ((k, v) in params) {
            text = text.replace("{$k}", v.toString())
        }
        return text
    }
